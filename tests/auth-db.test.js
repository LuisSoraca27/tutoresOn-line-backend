  const filtroBarato = await (await fetch(`${api}/tutores?materia_id=programacion&nivel_id=tecnico&precio_max=30000&q=programacion`)).json();
  assert.equal(filtroBarato.items.some((t) => t.id === tutor.usuario.id), true);
  const expressUrl = `${api}/express`;
  const ticket = async (headers) => {
    const response = await fetch(`${expressUrl}/ticket`, { method: "POST", headers });
    assert.equal(response.status, 200);
    return (await response.json()).ticket;
  };
  const abrir = async (headers) => {
    const value = await ticket(headers);
    const ws = new WebSocket(`ws://127.0.0.1:${server.address().port}/api/v1/express/socket?ticket=${value}`, { origin: config.frontendOrigin });
    await new Promise((resolve, reject) => { ws.once("open", resolve); ws.once("error", reject); });
    return ws;
  };
  const cambio = (ws) => new Promise((resolve, reject) => {
    const timeout = setTimeout(() => { ws.off("message", recibir); reject(new Error("No llegó el aviso WebSocket.")); }, 5000);
    function recibir(data) { if (JSON.parse(data.toString()).tipo === "cambio") { clearTimeout(timeout); ws.off("message", recibir); resolve(); } }
    ws.on("message", recibir);
  });
  assert.equal((await fetch(`${expressUrl}/ticket`, { method: "POST" })).status, 401);
  const denegado = (value, origin) => new Promise((resolve, reject) => {
    const ws = new WebSocket(`ws://127.0.0.1:${server.address().port}/api/v1/express/socket?ticket=${value}`, { origin });
    const limite = setTimeout(() => { ws.terminate(); reject(new Error("No se rechazó el WebSocket.")); }, 5000);
    ws.once("open", () => { clearTimeout(limite); ws.terminate(); reject(new Error("Se aceptó un WebSocket no autorizado.")); });
    ws.once("error", () => { clearTimeout(limite); resolve(); });
  });
  const ticketAjeno = await ticket(estudianteHeaders);
  await denegado(ticketAjeno, "http://origen-ajeno.example");
  await denegado(ticketAjeno, config.frontendOrigin);
  const socketEstudiante = await abrir(estudianteHeaders);
  const socketTutor = await abrir(tutorHeaders);
  const socketOtro = await abrir(otherHeaders);
  const primeraConexion = cambio(socketEstudiante);
  socketTutor.send(JSON.stringify({ tipo: "disponible", valor: true }));
  await primeraConexion;
  assert.equal((await (await fetch(`${api}/tutores/${tutor.usuario.id}`)).json()).disponibleAhora, true);
  const segundaConexion = cambio(socketEstudiante);
  socketOtro.send(JSON.stringify({ tipo: "disponible", valor: true }));
  await segundaConexion;
  const entrada = { materiaId: "calculo", nivelId: "universitario", modalidad: "virtual", duracionMinutos: 60, nota: "Ayuda con derivadas" };
  const lanzar = (body, headers = estudianteHeaders) => fetch(expressUrl, { method: "POST", headers: { ...headers, "Content-Type": "application/json" }, body: JSON.stringify(body) });
  assert.equal((await lanzar({ ...entrada, modalidad: "presencial" })).status, 400);
  const avisoTutor = cambio(socketTutor);
  const respuestaExpress = await lanzar(entrada);
  assert.equal(respuestaExpress.status, 201, await respuestaExpress.clone().text());
  const express = await respuestaExpress.json();
  await avisoTutor;
  assert.equal((await lanzar(entrada)).status, 409);
  assert.equal((await fetch(`${expressUrl}/${express.id}`, { headers: otraHeaders })).status, 404);
  const estadoBuscando = await (await fetch(`${expressUrl}/${express.id}`, { headers: estudianteHeaders })).json();
  assert.deepEqual(new Set(estadoBuscando.candidatos.map((t) => t.id)), new Set([tutor.usuario.id, other.usuario.id]));
  const activasTutor = await (await fetch(expressUrl, { headers: tutorHeaders })).json();
  assert.ok(activasTutor.some((s) => s.id === express.id));
  const avisoEstudiante = cambio(socketEstudiante);
  const tomar = (headers) => fetch(`${expressUrl}/${express.id}/tomar`, { method: "POST", headers });
  const tomadas = await Promise.all([tomar(tutorHeaders), tomar(otherHeaders)]);
  assert.deepEqual(tomadas.map((r) => r.status).sort(), [200, 409]);
  await avisoEstudiante;
  const estadoExpress = await (await fetch(`${expressUrl}/${express.id}`, { headers: estudianteHeaders })).json();
  assert.equal(estadoExpress.solicitud.estado, "emparejada");
  const reservaExpress = await prisma.booking.findUnique({ where: { id: estadoExpress.solicitud.reservaId } });
  assert.equal(reservaExpress.status, "accepted");
  assert.equal(reservaExpress.studentId, ids[0]);
  assert.equal(reservaExpress.tutorId, estadoExpress.solicitud.tutorId);
  assert.equal((await fetch(`${expressUrl}/${express.id}/cancelar`, { method: "POST", headers: estudianteHeaders })).status, 409);
  const avisoSegunda = cambio(socketEstudiante);
  const segundaBusqueda = await lanzar(entrada);
  await avisoSegunda;
  assert.equal(segundaBusqueda.status, 201);
  const paraCancelar = await segundaBusqueda.json();
  const ganadorHeaders = reservaExpress.tutorId === tutor.usuario.id ? tutorHeaders : otherHeaders;
  assert.equal((await fetch(`${expressUrl}/${paraCancelar.id}/tomar`, { method: "POST", headers: ganadorHeaders })).status, 409);
  assert.equal((await (await fetch(`${expressUrl}/activa`, { headers: estudianteHeaders })).json()).id, paraCancelar.id);
  assert.equal((await fetch(`${expressUrl}/${paraCancelar.id}/cancelar`, { method: "POST", headers: otraHeaders })).status, 404);
  const avisoCancelacion = cambio(socketEstudiante);
  assert.equal((await fetch(`${expressUrl}/${paraCancelar.id}/cancelar`, { method: "POST", headers: estudianteHeaders })).status, 204);
  await avisoCancelacion;
  assert.equal((await (await fetch(`${expressUrl}/${paraCancelar.id}`, { headers: estudianteHeaders })).json()).solicitud.estado, "cancelada");
  const avisoTercera = cambio(socketEstudiante);
  const terceraBusqueda = await (await lanzar(entrada)).json();
  await avisoTercera;
  await prisma.instantTutoringRequest.update({ where: { id: terceraBusqueda.id }, data: { createdAt: new Date(Date.now() - 6 * 60000) } });
  const avisoVencimiento = cambio(socketEstudiante);
  assert.equal((await (await fetch(`${expressUrl}/${terceraBusqueda.id}`, { headers: estudianteHeaders })).json()).solicitud.estado, "expirada");
  await avisoVencimiento;
  const desconexion = cambio(socketEstudiante);
  socketTutor.close();
  await desconexion;
  assert.equal((await (await fetch(`${api}/tutores/${tutor.usuario.id}`)).json()).disponibleAhora, false);
